// Keep the worker as a native ES module: CRA's relative publicPath otherwise
// resolves shared worker chunks against static/js/ twice on nested hosting.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
let worker = fs.readFileSync(path.join(root, "src/house.worker.js"), "utf8");
const marker = 'import data from "./data/house2026.json";';
if (!worker.includes(marker))
  throw new Error(
    "House worker data import changed; update the preparation script.",
  );
const data = JSON.parse(
  fs.readFileSync(path.join(root, "src/data/house2026.json")),
);
worker = worker.replace(marker, `const data = ${JSON.stringify(data)};`);
fs.writeFileSync(
  path.join(root, "public/house-worker.mjs"),
  "// Generated by scripts/prepare_house_worker.cjs.\n" + worker,
);
fs.writeFileSync(
  path.join(root, "public/house-model.mjs"),
  fs
    .readFileSync(path.join(root, "src/house-model.mjs"), "utf8")
    .replace('from "./model.mjs"', 'from "./election-model.mjs"'),
);
fs.copyFileSync(
  path.join(root, "src/model.mjs"),
  path.join(root, "public/election-model.mjs"),
);
console.log("Prepared native House worker and model modules.");
